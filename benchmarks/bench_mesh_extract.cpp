// Group N task 44: mesh extraction as a standing regression baseline. Not re-litigating the
// already-fixed NeighborCache incident -- this exists so the NEXT extraction regression is caught
// by a number in a diff, not by a stalled frame someone happens to notice.
#include <cstddef>
#include <cstdint>

#include <benchmark/benchmark.h>

#include "world/chunk/chunk_coord.hpp"
#include "world/chunk/chunk_store.hpp"
#include "world/generation/heightmap_generator.hpp"
#include "world/generation/terrain_fill.hpp"
#include "world/meshing/mesh_extractor.hpp"

namespace {

using world::chunk::ChunkCoord;

void BM_extract_mesh_terrain(benchmark::State& state) {
    // A real surface chunk (y=0 crosses the terrain band) with its full 27-halo, generated by the
    // real pipeline at the default seed -- the same work one streaming mesh job performs.
    world::generation::HeightmapGenerator heightmap(1337);
    world::chunk::ChunkStore store;
    const ChunkCoord center{0, 0, 0};
    for (std::int32_t dz = -1; dz <= 1; ++dz) {
        for (std::int32_t dy = -1; dy <= 1; ++dy) {
            for (std::int32_t dx = -1; dx <= 1; ++dx) {
                world::generation::fill_terrain(
                    store.get_or_create(ChunkCoord{center.x + dx, center.y + dy, center.z + dz}), heightmap);
            }
        }
    }

    std::size_t vertices = 0;
    for (auto _ : state) {
        // Non-const on purpose: MSVC's DoNotOptimize deprecates the const-ref overload ("can
        // permit undesired compiler optimizations") -- Subagent 2's flagged caveat, confirmed
        // here as a real /WX build break.
        auto mesh = world::meshing::extract_mesh(store, center);
        vertices = mesh.vertices.size();
        benchmark::DoNotOptimize(mesh);
    }
    state.counters["vertices"] = static_cast<double>(vertices);
}

BENCHMARK(BM_extract_mesh_terrain)->Unit(benchmark::kMillisecond);

} // namespace
